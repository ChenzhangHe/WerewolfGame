'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const source = fs.readFileSync(path.join(__dirname, '../web/app.js'), 'utf8');
const context = vm.createContext({});
vm.runInContext(source.split('// BEGIN PUBLIC ELECTION MARKS')[1].split('// END PUBLIC ELECTION MARKS')[0], context);
const mark = context.publicElectionMarks;
const players = Array.from({length:12}, (_, n) => ({seat:n+1,alive:true}));
const event = (kind, data, extra={}) => ({kind,data,audience:'public',...extra});
const nominations = event('nominations', {candidates:[1,3,7]});
assert.equal(mark([], players).size,0);
assert.equal(mark([{...nominations,audience:'private'}],players).size,0);
assert.equal(mark([event('speech',{}, {text:'I am running for Sheriff.'})],players).size,0);
assert.equal(mark([nominations],players).get(1),'candidate');
assert.equal(mark([nominations,event('explosion',{}, {seat:7}),event('night',{})],players.map(p=>({...p,alive:p.seat!==7}))).get(7),'nominated');
assert.equal(mark([nominations,event('night',{})],players).get(1),'candidate');
let marks=mark([nominations,event('explosion',{}, {seat:7}),event('withdrawals',{candidates:[3]})],players);
assert.equal(marks.get(1),'withdrawn'); assert.equal(marks.get(3),'candidate'); assert.equal(marks.get(7),'nominated');
marks=mark([nominations,event('sheriff_ballots',{tally:{1:2,3:2,7:1}})],players);
assert.equal(marks.get(1),'candidate');assert.equal(marks.get(3),'candidate');assert.equal(marks.get(7),'nominated');
marks=mark([nominations,event('withdrawals',{candidates:[3]}),event('sheriff',{sheriff:3})],players);
assert.equal(marks.get(3),'elected');assert.equal(marks.get(1),'withdrawn');
assert.equal(mark([nominations],players,true).get(1),'nominated');
assert.equal(mark([nominations,event('sheriff',{sheriff:null})],players).get(1),'nominated');
console.log('Public election badges: publication, withdrawals, interruption, runoff, completion and replay checks passed.');
